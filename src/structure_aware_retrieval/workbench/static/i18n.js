  const storageKey = "sacr.workbench.language";
  const supported = value => value === "en" || value === "zh-CN";
  let saved;
  try { saved = localStorage.getItem(storageKey); } catch { /* Session-only preference. */ }
  const preferred = navigator.languages?.[0] || navigator.language || "en";
  let language = supported(saved) ? saved : /^zh(?:-|$)/i.test(preferred) ? "zh-CN" : "en";
  function t(key, values = {}) {
    const current = catalogs[language];
    const message = Object.hasOwn(current, key) ? current[key] : Object.hasOwn(catalogs.en, key) ? catalogs.en[key] : key;
    // Single substitution pass. Parameter text never becomes a template or HTML.
    return message.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
  }
  function apply(root = document) {
    for (const element of root.querySelectorAll("[data-i18n]")) element.textContent = t(element.dataset.i18n);
    for (const [attribute, name] of [["data-i18n-placeholder", "placeholder"], ["data-i18n-aria-label", "aria-label"], ["data-i18n-title", "title"]]) {
      for (const element of root.querySelectorAll(`[${attribute}]`)) element.setAttribute(name, t(element.getAttribute(attribute)));
    }
    document.documentElement.lang = language;
    document.title = t("app.title");
    const select = document.getElementById("language-select");
    if (select) select.value = language;
  }
  function setLanguage(value) {
    if (!supported(value)) return;
    try { localStorage.setItem(storageKey, value); } catch { /* Still switch in this page. */ }
    if (value === language) return;
    language = value;
    apply();
    window.dispatchEvent(new CustomEvent("workbench-language-change", { detail: { language } }));
  }
  window.WorkbenchI18n = { catalogs, errorKeys, getLanguage: () => language, setLanguage, t, apply };
  apply();
  document.getElementById("language-select")?.addEventListener("change", event => setLanguage(event.target.value));
